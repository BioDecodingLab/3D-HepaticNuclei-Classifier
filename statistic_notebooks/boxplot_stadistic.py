baseline_values = pivot_df[best_experiment].values

posthoc_rows = []

for exp in pivot_df.columns:
    if exp == best_experiment:
        continue

    comparison_values = pivot_df[exp].values

    if np.allclose(baseline_values, comparison_values):
        stat = 0.0
        p_value = 1.0
    else:
        try:
            stat, p_value = wilcoxon(
                baseline_values,
                comparison_values,
                zero_method="wilcox",
                alternative="two-sided",
                mode="auto"
            )
        except ValueError:
            stat = np.nan
            p_value = 1.0

    baseline_mean = np.mean(baseline_values)
    comparison_mean = np.mean(comparison_values)

    posthoc_rows.append({
        "baseline_best_experiment": best_experiment,
        "comparison": exp,
        "baseline_mean": baseline_mean,
        "comparison_mean": comparison_mean,
        "mean_difference": baseline_mean - comparison_mean,
        "wilcoxon_statistic": stat,
        "p_value_raw": p_value
    })

posthoc_df = pd.DataFrame(posthoc_rows)

reject, pvals_corrected, _, _ = multipletests(
    posthoc_df["p_value_raw"].values,
    alpha=0.05,
    method="holm"
)

