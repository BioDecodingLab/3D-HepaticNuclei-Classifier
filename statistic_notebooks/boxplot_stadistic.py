def paired_cohens_d_for_table(baseline_values, comparison_values):
    differences = baseline_values - comparison_values
    mean_difference = np.mean(differences)
    std_difference = np.std(differences, ddof=1)

    if std_difference == 0:
        return np.nan, mean_difference

    cohens_d = mean_difference / std_difference
    return cohens_d, mean_difference


def interpret_effect_size(d):
    if pd.isna(d):
        return "undefined effect"

    abs_d = abs(d)

    if abs_d < 0.2:
        return "negligible effect"
    elif abs_d < 0.5:
        return "small effect"
    elif abs_d < 0.8:
        return "medium effect"
    else:
        return "large effect"


def interpret_professor_result(mean_difference, cohens_d, p_value, alpha=0.05):
    effect_text = interpret_effect_size(cohens_d)

    if pd.isna(p_value):
        return f"Wilcoxon not available; {effect_text}"

    if p_value < alpha:
        if mean_difference > 0:
            return f"Baseline model significantly better; {effect_text}"
        elif mean_difference < 0:
            return f"Comparison model significantly better; {effect_text}"

    return f"No significant difference; {effect_text}"


