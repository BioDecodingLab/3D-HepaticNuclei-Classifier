# 14.3 CREATE ONE TABLE PER METRIC
# ============================================================

METRIC_NAMES_FOR_TABLE = {
    "f1_macro": "Macro-F1",
    "f1_weighted": "Weighted-F1",
    "balanced_accuracy": "Balanced Accuracy"
}

professor_tables = {}
professor_paths = []

for metric_col in METRIC_COLS:

    pivot_df = all_models_df.pivot_table(
        index="fold",
        columns="display_label",
        values=metric_col,
        aggfunc="mean"
    )

    if baseline_model not in pivot_df.columns:
        raise ValueError(f"Baseline model not found in pivot table for {metric_col}")

    rows = []

    for comparison_model in pivot_df.columns:

        if comparison_model == baseline_model:
            continue

        paired_df = pivot_df[[baseline_model, comparison_model]].dropna()

        if paired_df.shape[0] < 2:
            continue

        baseline_values = paired_df[baseline_model].values
        comparison_values = paired_df[comparison_model].values

        cohens_d, mean_difference = paired_cohens_d_for_table(
            baseline_values,
            comparison_values
        )

        try:
            wilcoxon_statistic, wilcoxon_p_value = wilcoxon(
                baseline_values,
                comparison_values,
                zero_method="wilcox",
                alternative="two-sided",
                mode="auto"
            )
        except ValueError:
            wilcoxon_statistic = np.nan
            wilcoxon_p_value = np.nan

        rows.append({
            "Metric": METRIC_NAMES_FOR_TABLE.get(metric_col, metric_col),
            "Comparison": (
                f"{clean_label_for_display(baseline_model)} "
                f"vs {clean_label_for_display(comparison_model)}"
            ),
            "Mean difference": mean_difference,
            "Cohen's d": cohens_d,
            "Wilcoxon p-value": wilcoxon_p_value,
            "Interpretation": interpret_professor_result(
                mean_difference,
                cohens_d,
                wilcoxon_p_value
            )
        })

    metric_table = pd.DataFrame(rows)

    metric_table = metric_table.sort_values(
        by="Mean difference",
        ascending=False
    ).reset_index(drop=True)

    metric_table_rounded = metric_table.copy()
    metric_table_rounded["Mean difference"] = metric_table_rounded["Mean difference"].round(4)
    metric_table_rounded["Cohen's d"] = metric_table_rounded["Cohen's d"].round(4)
    metric_table_rounded["Wilcoxon p-value"] = metric_table_rounded["Wilcoxon p-value"].round(4)

    professor_tables[metric_col] = metric_table_rounded

    output_csv_path = os.path.join(
        PROFESSOR_TABLE_DIR,
        f"professor_table_{metric_col}.csv"
    )

