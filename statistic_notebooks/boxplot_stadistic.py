def paired_cohens_d(x, y):
    diff = x - y
    mean_diff = np.mean(diff)
    std_diff = np.std(diff, ddof=1)

    if std_diff == 0:
        return np.nan, mean_diff, std_diff

    d = mean_diff / std_diff
    return d, mean_diff, std_diff


def interpret_cohens_d(d):
    if pd.isna(d):
        return "undefined"

    abs_d = abs(d)

    if abs_d < 0.2:
        return "negligible"
    elif abs_d < 0.5:
        return "small"
    elif abs_d < 0.8:
        return "medium"
    else:
        return "large"


