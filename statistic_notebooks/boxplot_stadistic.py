def build_paired_matrix(data, metric_col, order):
    pivot_df = data.pivot_table(
        index="fold",
        columns="display_label",
        values=metric_col,
        aggfunc="mean"
    )

    available_order = [
        item for item in order
        if item in pivot_df.columns
    ]

    pivot_df = pivot_df[available_order]
    pivot_df = pivot_df.dropna(axis=0, how="any")

    return pivot_df


