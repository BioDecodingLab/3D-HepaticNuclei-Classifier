def normalize_text(x):
    x = str(x).strip().lower()
    x = x.replace("-", "_")
    x = x.replace(" ", "_")
    return x


def flatten_json(d, parent_key="", sep="_"):
    items = {}

    if isinstance(d, dict):
        for k, v in d.items():
            new_key = f"{parent_key}{sep}{k}" if parent_key else str(k)
            items.update(flatten_json(v, new_key, sep=sep))

    elif isinstance(d, list):
        for i, v in enumerate(d):
            new_key = f"{parent_key}{sep}{i}" if parent_key else str(i)
            items.update(flatten_json(v, new_key, sep=sep))

    else:
        items[parent_key] = d

    return items


def find_metric_value(flat_data, metric_name):
    metric_norm = normalize_text(metric_name)

    normalized_data = {
        normalize_text(k): v
        for k, v in flat_data.items()
    }

    possible_names = [
        f"test_{metric_norm}",
        f"test_metrics_{metric_norm}",
        f"metrics_test_{metric_norm}",
        f"summary_test_{metric_norm}",
        metric_norm,
        f"metrics_{metric_norm}",
        f"summary_{metric_norm}"
    ]

    for name in possible_names:
        if name in normalized_data:
            return normalized_data[name]

    for k, v in normalized_data.items():
        if k.endswith(f"test_{metric_norm}"):
            return v

    for k, v in normalized_data.items():
        if k.endswith(metric_norm):
            return v

    return None


