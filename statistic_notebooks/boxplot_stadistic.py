def parse_augmentation(folder_name):
    m = re.match(r"cv_benchmark_results_(.+?)_cv$", folder_name.lower())
    return m.group(1) if m else None


def make_experiment_label(model, augmentation):
    short_model = LABEL_MAP.get(str(model).strip(), str(model).strip())
    aug = str(augmentation).strip().lower()

    if aug == "noaug":
        return short_model

    return f"{short_model} +{aug}"


def find_metrics_summary_file(fold_dir):
    for fname in os.listdir(fold_dir):
        low = fname.lower()

        if low == "metrics_summary" or low == "metrics_summary.csv":
            return os.path.join(fold_dir, fname)

    for fname in os.listdir(fold_dir):
        if "metrics_summary" in fname.lower():
            return os.path.join(fold_dir, fname)

    return None


def read_metrics_summary(file_path):
    try:
        df = pd.read_csv(file_path)
    except Exception:
        df = pd.read_csv(file_path, sep=None, engine="python")

    df.columns = [str(c).strip().lower() for c in df.columns]

    if "split" not in df.columns:
        raise ValueError(f"No existe columna 'split' en {file_path}")

    df["split"] = df["split"].astype(str).str.strip().str.lower()

    test_row = df[df["split"] == "test"]

    if test_row.empty:
        raise ValueError(f"No se encontró fila 'Test' en {file_path}")

    test_row = test_row.iloc[0]

    result = {}

    for metric in TARGET_METRICS:
        result[metric] = pd.to_numeric(test_row.get(metric, None), errors="coerce")

    return result


